// Package tz is the only source of zone data in the gateway: the embedded
// IANA release that production Node's ICU carries, never the host's
// /usr/share/zoneinfo and never a ZONEINFO directory.
//
// The host's tzdata package and Node's ICU move independently. On 2026-11-25
// the host moved to tzdata 2026f, which extends Cuba's DST to 2027-11-07, while
// production Node 24.22.3 (ICU 78.3) still ends it on 2026-11-01. A gateway
// that read the host's zones then computed a spending period start of 04:00Z
// for America/Havana where the TypeScript workers, using Intl, computed
// 05:00Z. Every zone lookup therefore answers from zoneinfo.zip, generated by
// genzones from the pinned IANA release; TestNodeVersionProvenance fails when
// production's process.versions.tz no longer matches the pin.
//
// Go's own time.LoadLocation consults ZONEINFO, then /usr/share/zoneinfo, then
// its embedded copy from time/tzdata; none of those may be used. The Go
// standard library still supplies the TZif parser via
// time.LoadLocationFromTZData, which reads only the bytes it is given.
package tz

import (
	"archive/zip"
	"bytes"
	_ "embed"
	"fmt"
	"os"
	"sort"
	"strings"
	"sync"
	"time"
)

//go:embed zoneinfo.zip
var zoneinfoZip []byte

//go:generate go run ./genzones

// database is the parsed zoneinfo.zip index. Zones are parsed on first use.
type database struct {
	files map[string]*zip.File
	lower map[string]string
	names []string
}

var open = sync.OnceValue(func() *database {
	reader, err := zip.NewReader(bytes.NewReader(zoneinfoZip), int64(len(zoneinfoZip)))
	if err != nil {
		panic("tz: embedded zoneinfo.zip is unreadable: " + err.Error())
	}
	db := &database{files: make(map[string]*zip.File, len(reader.File)), lower: make(map[string]string, len(reader.File))}
	for _, file := range reader.File {
		if strings.HasSuffix(file.Name, "/") {
			continue
		}
		db.files[file.Name] = file
		db.names = append(db.names, file.Name)
	}
	// Intl resolves names case-insensitively. Should two names differ only by
	// case, the sorted-first one wins deterministically.
	sort.Strings(db.names)
	for _, name := range db.names {
		key := strings.ToLower(name)
		if _, taken := db.lower[key]; !taken {
			db.lower[key] = name
		}
	}
	return db
})

// Names is every zone the embedded database carries, sorted: the IANA zones
// and the aliases from the release's backward file.
func Names() []string {
	return append([]string(nil), open().names...)
}

// Has reports whether the embedded database carries name, case-insensitively.
func Has(name string) bool {
	_, ok := resolve(name)
	return ok
}

var (
	cacheMu sync.Mutex
	cache   = map[string]*time.Location{}
)

// Load returns the zone the embedded tzdata release defines under name, or an
// error when the release has no such zone. It never falls back to the host.
func Load(name string) (*time.Location, error) {
	entry, ok := resolve(name)
	if !ok {
		return nil, fmt.Errorf("tz: zone %q is not in the embedded tzdata %s database", name, Version)
	}
	cacheMu.Lock()
	defer cacheMu.Unlock()
	if location, ok := cache[entry]; ok {
		return location, nil
	}
	file, err := open().files[entry].Open()
	if err != nil {
		return nil, fmt.Errorf("tz: open %q: %w", entry, err)
	}
	defer file.Close()
	var data bytes.Buffer
	// A zone file is a few kilobytes; the buffer starts there and never shrinks.
	data.Grow(int(open().files[entry].UncompressedSize64))
	if _, err := data.ReadFrom(file); err != nil {
		return nil, fmt.Errorf("tz: read %q: %w", entry, err)
	}
	location, err := time.LoadLocationFromTZData(entry, data.Bytes())
	if err != nil {
		return nil, fmt.Errorf("tz: parse %q: %w", entry, err)
	}
	cache[entry] = location
	return location, nil
}

// resolve maps a requested name to its zip entry, exactly or
// case-insensitively. The name never reaches the filesystem: absolute paths,
// parent references and Go's "Local" are refused before the lookup.
func resolve(name string) (string, bool) {
	if name == "" || name == "Local" || strings.Contains(name, "..") ||
		strings.HasPrefix(name, "/") || strings.HasPrefix(name, `\`) ||
		strings.ContainsAny(name, "\\\x00") {
		return "", false
	}
	db := open()
	if _, ok := db.files[name]; ok {
		return name, true
	}
	entry, ok := db.lower[strings.ToLower(name)]
	return entry, ok
}

var (
	localOnce sync.Once
	local     *time.Location
)

// Local is the zone a datetime without an offset is read in, matching the zone
// V8's Date uses: the TZ environment variable, else the zone /etc/localtime
// names, else UTC. Only the zone name comes from the process; its rules always
// come from the embedded database, and a name the release no longer carries
// reads as UTC.
func Local() *time.Location {
	localOnce.Do(func() {
		local = resolveLocal(os.Getenv, os.Readlink)
	})
	return local
}

// resolveLocal is Local with the process sources injected, so the fallback
// chain is testable without touching the host.
func resolveLocal(getenv func(string) string, readlink func(string) (string, error)) *time.Location {
	if name := strings.TrimPrefix(getenv("TZ"), ":"); name != "" {
		if location, err := Load(name); err == nil {
			return location
		}
		return time.UTC
	}
	target, err := readlink("/etc/localtime")
	if err != nil {
		return time.UTC
	}
	for _, marker := range []string{"/zoneinfo/", "/zoneinfo64/"} {
		if index := strings.LastIndex(target, marker); index >= 0 {
			if location, err := Load(target[index+len(marker):]); err == nil {
				return location
			}
			return time.UTC
		}
	}
	return time.UTC
}
