// Package gentables generates the catalog-derived tables the model DTOs need: the Anthropic
// thinking-level lists (from @earendil-works/pi-ai's provider data) and the hosted
// openai-compatible endpoint presets (from the TypeScript source). tools/gen-model-tables wraps
// it and the drift test compares the committed output with a fresh generation.
package gentables

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// thinkingOrders is the extended level list pi-ai filters over, in order.
var thinkingOrders = []string{"off", "minimal", "low", "medium", "high", "xhigh", "max"}

type anthropicModel struct {
	ID             string             `json:"id"`
	API            string             `json:"api"`
	Provider       string             `json:"provider"`
	Reasoning      bool               `json:"reasoning"`
	Input          []string           `json:"input"`
	ThinkingLevels map[string]*string `json:"thinkingLevelMap"`
}

// catalogModelGen is one model the pinned pi-ai provider data describes.
type catalogModelGen struct {
	Provider string
	ID       string
	Images   bool
	Levels   []string
}

// Generate returns the Go source for the generated tables file.
func Generate(piPath, presetPath string) ([]byte, error) {
	anthropic, err := anthropicLevels(piPath)
	if err != nil {
		return nil, err
	}
	presets, err := endpointPresets(presetPath)
	if err != nil {
		return nil, err
	}
	catalog, err := catalogModels(filepath.Dir(piPath))
	if err != nil {
		return nil, err
	}

	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by tools/gen-model-tables from the pinned @earendil-works/pi-ai\n")
	buffer.WriteString("// anthropic provider data and the TypeScript endpoint presets; DO NOT EDIT.\n\n")
	buffer.WriteString("package modelcredentials\n\n")
	buffer.WriteString("// anthropicThinkingLevels is getSupportedThinkingLevels over the pinned Anthropic catalog's\n")
	buffer.WriteString("// thinkingLevelMap for each model it describes (anthropicCatalogThinking copies the map).\n")
	buffer.WriteString("var anthropicThinkingLevels = map[string][]string{\n")
	ids := make([]string, 0, len(anthropic))
	for id := range anthropic {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		buffer.WriteString(fmt.Sprintf("\t%s: %s,\n", quote(id), stringSlice(anthropic[id])))
	}
	buffer.WriteString("}\n\n")
	buffer.WriteString("// compatibleEndpointPresets mirrors COMPATIBLE_ENDPOINT_PRESETS (hosted compatible services).\n")
	buffer.WriteString("var compatibleEndpointPresets = []compatibleEndpointPreset{\n")
	for _, preset := range presets {
		buffer.WriteString(fmt.Sprintf("\t{Name: %s, BaseURL: %s},\n", quote(preset[0]), quote(preset[1])))
	}
	buffer.WriteString("}\n\n")
	buffer.WriteString("// catalogModels is listPiCatalog's model metadata from the pinned pi-ai provider data:\n")
	buffer.WriteString("// whether the model reads images, and the thinking levels it accepts (empty means off only).\n")
	buffer.WriteString("var catalogModels = []catalogModel{\n")
	for _, model := range catalog {
		buffer.WriteString(fmt.Sprintf("\t{%s, %s, %t, %s},\n",
			quote(model.Provider), quote(model.ID), model.Images, quote(strings.Join(model.Levels, ","))))
	}
	buffer.WriteString("}\n")

	formatted, err := format.Source(buffer.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated tables: %w", err)
	}
	return formatted, nil
}

// catalogModels reads every provider data file next to anthropic.json. Models are sorted by
// provider and id; a duplicate (provider, id) keeps the first file's row.
func catalogModels(directory string) ([]catalogModelGen, error) {
	paths, err := filepath.Glob(filepath.Join(directory, "*.json"))
	if err != nil {
		return nil, err
	}
	byKey := map[string]catalogModelGen{}
	for _, path := range paths {
		if strings.HasPrefix(filepath.Base(path), ".") {
			continue
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		var data map[string]json.RawMessage
		if err := json.Unmarshal(raw, &data); err != nil {
			return nil, fmt.Errorf("parse %s: %w", path, err)
		}
		for _, rawProvider := range data {
			entries, err := modelEntries(rawProvider)
			if err != nil {
				return nil, fmt.Errorf("parse %s: %w", path, err)
			}
			for _, entry := range entries {
				var model anthropicModel
				if err := json.Unmarshal(entry, &model); err != nil {
					return nil, fmt.Errorf("parse a model in %s: %w", path, err)
				}
				if model.ID == "" || model.Provider == "" {
					continue
				}
				key := model.Provider + "\x00" + model.ID
				levels := []string{"off"}
				if model.Reasoning {
					levels = supportedLevels(model.ThinkingLevels)
				}
				images := false
				for _, input := range model.Input {
					if input == "image" {
						images = true
					}
				}
				candidate := catalogModelGen{
					Provider: model.Provider, ID: model.ID, Images: images, Levels: levels,
				}
				// The same provider/model can appear under two APIs. Keep the richer entry,
				// whatever order the files are read in: the one that reasons, then the one
				// with more thinking levels.
				current, present := byKey[key]
				if !present || (len(candidate.Levels) > len(current.Levels)) {
					byKey[key] = candidate
				}
			}
		}
	}
	models := make([]catalogModelGen, 0, len(byKey))
	for _, model := range byKey {
		models = append(models, model)
	}
	sort.Slice(models, func(left, right int) bool {
		if models[left].Provider != models[right].Provider {
			return models[left].Provider < models[right].Provider
		}
		return models[left].ID < models[right].ID
	})
	return models, nil
}

// modelEntries reads a provider's data: a map keyed by "chat:<id>" (or a list in older
// versions).
func modelEntries(raw json.RawMessage) ([]json.RawMessage, error) {
	var byKey map[string]json.RawMessage
	var list []json.RawMessage
	if err := json.Unmarshal(raw, &byKey); err == nil && byKey != nil {
		for _, entry := range byKey {
			list = append(list, entry)
		}
		return list, nil
	}
	if err := json.Unmarshal(raw, &list); err != nil {
		return nil, err
	}
	return list, nil
}

func anthropicLevels(path string) (map[string][]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var data map[string]json.RawMessage
	if err := json.Unmarshal(raw, &data); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	rawProviders, ok := data["anthropic-messages"]
	if !ok {
		return nil, fmt.Errorf("%s has no anthropic-messages provider", path)
	}
	// The provider data is a map keyed by "chat:<id>" (and a list in older versions).
	var byKey map[string]json.RawMessage
	var list []json.RawMessage
	if err := json.Unmarshal(rawProviders, &byKey); err == nil && byKey != nil {
		for _, entry := range byKey {
			list = append(list, entry)
		}
	} else if err := json.Unmarshal(rawProviders, &list); err != nil {
		return nil, fmt.Errorf("parse %s anthropic-messages: %w", path, err)
	}
	levels := map[string][]string{}
	for _, entry := range list {
		var model anthropicModel
		if err := json.Unmarshal(entry, &model); err != nil {
			return nil, fmt.Errorf("parse an anthropic model: %w", err)
		}
		if model.ID == "" {
			continue
		}
		levels[model.ID] = supportedLevels(model.ThinkingLevels)
	}
	return levels, nil
}

// supportedLevels is pi-ai getSupportedThinkingLevels for a reasoning model: a null mapping drops
// the level, and xhigh/max exist only when the map names them.
func supportedLevels(mapping map[string]*string) []string {
	out := []string{}
	for _, level := range thinkingOrders {
		value, present := mapping[level]
		if present && value == nil {
			continue
		}
		if (level == "xhigh" || level == "max") && !present {
			continue
		}
		out = append(out, level)
	}
	return out
}

var presetEntry = regexp.MustCompile(`(?s)\{\s*name:\s*"([^"]+)",\s*baseUrl:\s*"([^"]+)",?\s*\}`)

func endpointPresets(path string) ([][2]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	source := string(raw)
	start := strings.Index(source, "COMPATIBLE_ENDPOINT_PRESETS")
	if start < 0 {
		return nil, fmt.Errorf("%s has no COMPATIBLE_ENDPOINT_PRESETS", path)
	}
	end := strings.Index(source[start:], "];")
	if end < 0 {
		return nil, fmt.Errorf("%s has no end of COMPATIBLE_ENDPOINT_PRESETS", path)
	}
	body := source[start : start+end]
	matches := presetEntry.FindAllStringSubmatch(body, -1)
	if len(matches) == 0 {
		return nil, fmt.Errorf("%s COMPATIBLE_ENDPOINT_PRESETS has no entries", path)
	}
	presets := make([][2]string, 0, len(matches))
	for _, match := range matches {
		presets = append(presets, [2]string{match[1], match[2]})
	}
	return presets, nil
}

func quote(value string) string {
	encoded, _ := json.Marshal(value)
	return string(encoded)
}

func stringSlice(values []string) string {
	parts := make([]string, len(values))
	for index, value := range values {
		parts[index] = quote(value)
	}
	return "{" + strings.Join(parts, ", ") + "}"
}
